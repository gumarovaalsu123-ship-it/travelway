/**
 * Словарь поиска на карте: по каким словам понять, что человек ищет не конкретное место, а категорию («отели»).
 *
 * Nominatim ищет по названиям: на «отель» он найдёт место, которое так и называется, а не все гостиницы вокруг.
 * Поэтому если запрос — слово из этого словаря, ищем по категории через Overpass (findInBox в overpass.js).
 *
 * set — ключ набора из PLACE_SETS (overpass.js), label — подпись на кнопке под строкой поиска.
 * words — начала слов (основы), чтобы подходили все падежи и число: «отел» → отель, отели, отелей.
 * Буква «ё» заменяется на «е» до сравнения, поэтому в основах пишем «е».
 */
export const SEARCH_CATEGORIES = [
    { set: 'hotels', label: 'Жильё', words: ['отел', 'гостиниц', 'хостел', 'мотел', 'апартамент', 'жиль', 'переночев', 'hotel', 'hostel'] },
    { set: 'food', label: 'Еда', words: ['кафе', 'ресторан', 'кофейн', 'столов', 'фастфуд', 'поесть', 'перекус', 'cafe', 'restaurant'] },
    { set: 'sights', label: 'Что посмотреть', words: ['достопримечательн', 'посмотр', 'памятник', 'монумент', 'мемориал', 'смотров', 'sight'] },
    { set: 'museums', label: 'Музеи', words: ['музе', 'галере', 'выставк', 'museum'] },
    { set: 'parks', label: 'Парки', words: ['парк', 'сквер', 'сад', 'погулят', 'прогулк', 'park'] },
    { set: 'groceries', label: 'Продукты', words: ['продукт', 'магазин', 'супермаркет', 'гастроном', 'минимаркет', 'supermarket'] },
    { set: 'pharmacies', label: 'Аптеки', words: ['аптек', 'лекарств', 'pharmacy'] },
];

/** Слова, которые не меняют смысла запроса: «отели рядом» — это то же, что «отели». */
const FILLER_WORDS = ['рядом', 'поблизости', 'близко', 'где', 'тут', 'здесь', 'что', 'и', 'в', 'на'];

/**
 * Слова, которые начинаются как категория, но значат другое: «парковка» — не парк, «кафедральный» — не кафе.
 * Если в запросе есть такое слово, ищем по названию.
 */
const NOT_CATEGORY_STEMS = ['парковк', 'паркинг', 'кафедр'];

/**
 * Категория для текста из строки поиска или null, если это поиск по названию или адресу.
 * Категория подходит, только если ВСЕ значимые слова запроса из её списка:
 * «отели рядом» → жильё, а «отель Ривьера» — это уже конкретное место, его ищем по названию.
 */
export function categoryForQuery(text) {
    const words = text
        .toLowerCase()
        .replaceAll('ё', 'е')
        .split(/[^a-zа-я0-9]+/)
        .filter((word) => word && !FILLER_WORDS.includes(word));

    if (words.length === 0 || words.some((word) => NOT_CATEGORY_STEMS.some((stem) => word.startsWith(stem)))) {
        return null;
    }

    return SEARCH_CATEGORIES.find(
        (category) => words.every((word) => category.words.some((stem) => word.startsWith(stem))),
    ) ?? null;
}
